"""05_make_snow_split_script.py

Classifies every cold-season scene (November to March, 2000 onward) as snow-covered,
snow-free or mixed, and writes a GEE script with the scene lists embedded, so GEE does
not have to recompute any per-scene statistics.

Inputs : data/scene_stats/<city>_scenes_used.csv and <city>_landsat_scene_stats_v2.csv
Outputs: data/scene_stats/cold_scene_snow_classes.csv
         gee/03_cold_snow_split.js
"""
import json
import os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATS = os.path.join(ROOT, "data", "scene_stats")
SNOW_MIN = 0.8     # snow-covered: at least 80% of the clear study area flagged as snow
NOSNOW_MAX = 0.1   # snow-free: at most 10%

frames, scenes = [], {}
for city in ["saskatoon", "regina"]:
    used = pd.read_csv(os.path.join(STATS, f"{city}_scenes_used.csv"))
    v2 = pd.read_csv(os.path.join(STATS, f"{city}_landsat_scene_stats_v2.csv"))
    v2 = v2[["scene_id", "clear_frac", "snow_frac"]].rename(columns={"clear_frac": "clear_frac_v2"})
    d = used.merge(v2, on="scene_id", how="left")
    d["date"] = pd.to_datetime(d["date"])
    cold = d["date"].dt.month.isin([11, 12, 1, 2, 3]) & (d["date"] >= "1999-11-01")
    d = d[cold].copy()
    d["snow_share"] = d["snow_frac"] / d["clear_frac_v2"]
    d["snow_class"] = "mixed"
    d.loc[d["snow_share"] >= SNOW_MIN, "snow_class"] = "snow"
    d.loc[d["snow_share"] <= NOSNOW_MAX, "snow_class"] = "nosnow"
    frames.append(d)

    scenes[city] = {}
    for cls in ["snow", "nosnow"]:
        rows = []
        for sid, mean in d.loc[d["snow_class"] == cls, ["scene_id", "mean_lst"]].itertuples(index=False):
            p = sid.split("_")            # LT05_L2SP_037024_19840415_20200918_02_T1
            rows.append([f"LANDSAT/{p[0]}/C02/T1_L2/{p[0]}_{p[2]}_{p[3]}", round(float(mean), 4)])
        scenes[city][cls] = rows

table = pd.concat(frames)
table.to_csv(os.path.join(STATS, "cold_scene_snow_classes.csv"), index=False)
print(table.groupby(["city", "snow_class"]).size().unstack())

JS = r"""// 03_cold_snow_split.js   (generated by scripts/05_make_snow_split_script.py; do not edit by hand)
// Cold-season (Nov-Mar, 2000-2026) composites split into snow-covered and snow-free scenes.
// The scene lists and each scene's study-area mean are embedded below, so the exports
// do not recompute any per-scene statistics and should be much faster than script 02.
//
// Paste into https://code.earthengine.google.com/ , press Run, then run the 4 tasks.
// Each export <city>_cold_<class>.tif has four bands:
//   lst       median land surface temperature, deg C
//   anom      median of (scene LST minus that scene's study-area mean), deg C
//   count     number of clear observations
//   snowfreq  share of those observations that an independent snow index (NDSI > 0.4)
//             calls snow; a check on the scene classification

var CITIES = {
  saskatoon: ee.Geometry.Point([-106.67, 52.13]),
  regina: ee.Geometry.Point([-104.61, 50.45])
};
var BUFFER_M = 20000;
var CRS = 'EPSG:32613';
var SCALE = 30;

// [asset id, study-area mean LST in deg C] for each scene.
var SCENES = __SCENES__;

function prep(pair) {
  var id = pair[0], mean = pair[1];
  var old = id.indexOf('LT05') > -1 || id.indexOf('LE07') > -1;   // Landsat 5 and 7 band names
  var img = ee.Image(id);
  var qa = img.select('QA_PIXEL');
  var st = img.select(old ? 'ST_B6' : 'ST_B10');
  var green = img.select(old ? 'SR_B2' : 'SR_B3').multiply(0.0000275).add(-0.2);
  var swir = img.select(old ? 'SR_B5' : 'SR_B6').multiply(0.0000275).add(-0.2);
  var clear = qa.bitwiseAnd(31).eq(0).and(st.neq(0));   // no fill, cloud or shadow
  var lst = st.multiply(0.00341802).add(149.0).subtract(273.15).rename('lst');
  var anom = lst.subtract(mean).rename('anom');
  var snow = green.subtract(swir).divide(green.add(swir)).gt(0.4).rename('snowfreq');
  return lst.addBands(anom).addBands(snow).updateMask(clear).toFloat();
}

Object.keys(SCENES).forEach(function (city) {
  var aoi = CITIES[city].buffer(BUFFER_M).bounds();
  Object.keys(SCENES[city]).forEach(function (cls) {
    var col = ee.ImageCollection(SCENES[city][cls].map(prep));
    var out = col.select(['lst', 'anom']).median()
      .addBands(col.select('lst').count().rename('count'))
      .addBands(col.select('snowfreq').mean())
      .toFloat();
    var name = city + '_cold_' + cls;
    print(name + ': scenes', SCENES[city][cls].length);
    Export.image.toDrive({
      image: out,
      description: name,
      folder: 'UHI_Prairie',
      fileNamePrefix: name,
      region: aoi,
      scale: SCALE,
      crs: CRS,
      maxPixels: 1e10
    });
    Map.addLayer(out.select('anom').clip(aoi),
      {min: -3, max: 4, palette: ['#2166ac', '#67a9cf', '#f7f7f7', '#ef8a62', '#b2182b']},
      name + ' anomaly', false);
  });
});

Map.setCenter(-106.67, 52.13, 11);
"""
body = json.dumps(scenes, indent=1).replace('[\n   "', '["').replace(',\n   ', ', ').replace('\n  ]', ']')
with open(os.path.join(ROOT, "gee", "03_cold_snow_split.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write(JS.replace("__SCENES__", body))
print("wrote gee/03_cold_snow_split.js")
