"""07_make_urban_rural_script.py

Writes gee/04_scene_urban_rural.js with the two municipal boundaries embedded.
The GEE script exports, for every Landsat scene, the mean surface temperature and snow
share of three zones: built-up land inside the city, other land inside the city, and
rural land outside a 2 km buffer. That table supports a per-scene test of whether the
city-minus-rural difference depends on snow cover once temperature and month are held fixed.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BND = os.path.join(ROOT, "data", "boundaries")

rings = {}
for city in ["saskatoon", "regina"]:
    with open(os.path.join(BND, f"{city}_osm_raw.geojson"), encoding="utf-8") as f:
        geom = json.load(f)["features"][0]["geometry"]
    assert geom["type"] == "Polygon", geom["type"]
    rings[city] = [[[round(x, 5), round(y, 5)] for x, y in ring] for ring in geom["coordinates"]]
    print(city, "rings:", len(rings[city]), "points:", sum(len(r) for r in rings[city]))

JS = r"""// 04_scene_urban_rural.js   (generated by scripts/07_make_urban_rural_script.py)
// Per-scene surface temperature and snow share for three zones in each city:
//   zone 1  built-up land inside the municipal boundary
//   zone 2  rural land: outside the boundary + 2 km, not built-up, not water
//   zone 3  other land inside the boundary (parks, fields; not built-up, not water)
// Built-up and water come from ESA WorldCover 2021.
//
// Paste into https://code.earthengine.google.com/ , press Run, then run the 2 tasks.
// Output: <city>_scene_zones.csv in the Drive folder UHI_Prairie. Each zone has four sums
// over 90 m cells: n (all cells), clear (clear cells), lst (deg C summed over clear cells)
// and snow (clear cells where the snow index NDSI exceeds 0.4). Means are taken later.

var BOUNDARIES = __RINGS__;
var CENTRES = {saskatoon: [-106.67, 52.13], regina: [-104.61, 50.45]};
var BUFFER_M = 20000;       // same 40 km box as the other scripts
var RURAL_GAP_M = 2000;     // rural zone starts this far outside the boundary
var SCALE = 90;
var L7_END = '2013-04-01';

var worldcover = ee.ImageCollection('ESA/WorldCover/v200').first().select('Map');
var built = worldcover.eq(50);
var water = worldcover.eq(80);

function load(aoi, id, st, green, swir, start, end) {
  return ee.ImageCollection(id).filterBounds(aoi).filterDate(start, end)
    .select([st, green, swir, 'QA_PIXEL'], ['ST', 'GREEN', 'SWIR', 'QA_PIXEL']);
}

Object.keys(BOUNDARIES).forEach(function (city) {
  var aoi = ee.Geometry.Point(CENTRES[city]).buffer(BUFFER_M).bounds();
  var boundary = ee.Geometry.Polygon(BOUNDARIES[city]);
  var inside = ee.Image.constant(0).byte().paint(ee.FeatureCollection([ee.Feature(boundary)]), 1);
  var near = ee.Image.constant(0).byte()
    .paint(ee.FeatureCollection([ee.Feature(boundary.buffer(RURAL_GAP_M))]), 1);
  var open = built.not().and(water.not());
  var zone = ee.Image.constant(0).byte()
    .where(inside.eq(1).and(built), 1)
    .where(near.eq(0).and(open), 2)
    .where(inside.eq(1).and(open), 3)
    .rename('zone');

  var scenes = load(aoi, 'LANDSAT/LT05/C02/T1_L2', 'ST_B6', 'SR_B2', 'SR_B5', '1984-01-01', '2012-06-01')
    .merge(load(aoi, 'LANDSAT/LE07/C02/T1_L2', 'ST_B6', 'SR_B2', 'SR_B5', '1999-01-01', L7_END))
    .merge(load(aoi, 'LANDSAT/LC08/C02/T1_L2', 'ST_B10', 'SR_B3', 'SR_B6', '2013-01-01', '2027-01-01'))
    .merge(load(aoi, 'LANDSAT/LC09/C02/T1_L2', 'ST_B10', 'SR_B3', 'SR_B6', '2021-01-01', '2027-01-01'));

  var table = scenes.map(function (img) {
    var st = img.select('ST');
    var clear = img.select('QA_PIXEL').bitwiseAnd(31).eq(0).and(st.neq(0));
    var lst = st.multiply(0.00341802).add(149.0).subtract(273.15);
    var green = img.select('GREEN').multiply(0.0000275).add(-0.2);
    var swir = img.select('SWIR').multiply(0.0000275).add(-0.2);
    var snow = green.subtract(swir).divide(green.add(swir)).gt(0.4);
    // Every band is unmasked, so the grouped sums all cover the same cells.
    var clear01 = clear.unmask(0);
    var stack = ee.Image.constant(1).rename('n')
      .addBands(clear01.rename('clear'))
      .addBands(lst.unmask(0).multiply(clear01).rename('lst'))
      .addBands(snow.unmask(0).multiply(clear01).rename('snow'))
      .addBands(zone).toFloat();
    var groups = ee.List(stack.reduceRegion({
      reducer: ee.Reducer.sum().repeat(4).group({groupField: 4, groupName: 'zone'}),
      geometry: aoi, scale: SCALE, maxPixels: 1e9, tileScale: 2
    }).get('groups'));
    var props = ee.Dictionary({
      city: city,
      scene_id: img.get('LANDSAT_PRODUCT_ID'),
      sensor: img.get('SPACECRAFT_ID'),
      date: img.date().format('YYYY-MM-dd'),
      sun_elevation: img.get('SUN_ELEVATION')
    });
    // Zones 0 to 3 are always present and come back in order.
    [1, 2, 3].forEach(function (z) {
      var sums = ee.List(ee.Dictionary(groups.get(z)).get('sum'));
      props = props
        .set('z' + z + '_n', sums.get(0)).set('z' + z + '_clear', sums.get(1))
        .set('z' + z + '_lst', sums.get(2)).set('z' + z + '_snow', sums.get(3));
    });
    return ee.Feature(null, props);
  });

  Export.table.toDrive({
    collection: ee.FeatureCollection(table),
    description: city + '_scene_zones',
    folder: 'UHI_Prairie',
    fileFormat: 'CSV'
  });
  Map.addLayer(zone.selfMask().clip(aoi), {min: 1, max: 3, palette: ['#d7191c', '#fdd49e', '#1a9641']},
    city + ' zones (red built, cream rural, green other city land)');
});

Map.setCenter(-106.67, 52.13, 10);
"""
out = os.path.join(ROOT, "gee", "04_scene_urban_rural.js")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(JS.replace("__RINGS__", json.dumps(rings, separators=(",", ":"))))
print("wrote", os.path.relpath(out, ROOT), os.path.getsize(out), "bytes")
