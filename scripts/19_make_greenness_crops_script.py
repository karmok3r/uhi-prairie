"""Write gee/05_rural_greenness_crops.js.

The GEE script measures, for every Landsat scene, the mean NDVI (and LST) of the same
zones used in gee/04_scene_urban_rural.js, and the yearly crop-type composition of the
rural zone from the AAFC Annual Crop Inventory (2009 onwards). It tests whether greening
or crop change of the rural reference explains part of the summer anomaly trend.

The municipal boundaries are copied from gee/04_scene_urban_rural.js so both scripts
use identical zones. Run with any Python 3:  python scripts/19_make_greenness_crops_script.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = (ROOT / "gee" / "04_scene_urban_rural.js").read_text(encoding="utf-8")
boundaries = next(line for line in src.splitlines() if line.startswith("var BOUNDARIES"))

JS = r"""// 05_rural_greenness_crops.js   (generated by scripts/19_make_greenness_crops_script.py)
// Tests whether change in the farmland around each city explains part of the summer
// LST anomaly trend.
//   Part A  per Landsat scene (April-September, 1984-2026): clear-sky mean NDVI and LST of
//           zone 1 built-up land in the city, zone 2 rural land (outside the boundary
//           + 2 km, not built-up, not water), zone 3 other city land, and zone 0 the rest.
//   Part B  per year (2009 onwards): pixel counts of every AAFC Annual Crop Inventory
//           class in the rural zone and in the whole 40 km box.
// Zones are identical to gee/04_scene_urban_rural.js.
//
// Paste into https://code.earthengine.google.com/ , press Run, then run the 4 tasks in
// the Tasks tab. Output (Drive folder UHI_Prairie):
//   <city>_scene_ndvi.csv   <city>_aci_classes.csv

__BOUNDARIES__
var CENTRES = {saskatoon: [-106.67, 52.13], regina: [-104.61, 50.45]};
var BUFFER_M = 20000;       // same 40 km box as the other scripts
var RURAL_GAP_M = 2000;
var SCALE = 90;
var L7_END = '2013-04-01';

var worldcover = ee.ImageCollection('ESA/WorldCover/v200').first().select('Map');
var built = worldcover.eq(50);
var water = worldcover.eq(80);

function load(aoi, id, st, red, nir, start, end) {
  return ee.ImageCollection(id).filterBounds(aoi).filterDate(start, end)
    .filter(ee.Filter.calendarRange(4, 9, 'month'))
    .select([st, red, nir, 'QA_PIXEL'], ['ST', 'RED', 'NIR', 'QA_PIXEL']);
}

Object.keys(BOUNDARIES).forEach(function (city) {
  var aoi = ee.Geometry.Point(CENTRES[city]).buffer(BUFFER_M).bounds();
  var boundary = ee.Geometry.Polygon(BOUNDARIES[city]);
  var inside = ee.Image.constant(0).byte().paint(ee.FeatureCollection([ee.Feature(boundary)]), 1);
  var near = ee.Image.constant(0).byte()
    .paint(ee.FeatureCollection([ee.Feature(boundary.buffer(RURAL_GAP_M))]), 1);
  var open = built.not().and(water.not());
  var zone = ee.Image.constant(0).byte()
    .where(inside.eq(1).and(built), 1)
    .where(near.eq(0).and(open), 2)
    .where(inside.eq(1).and(open), 3)
    .rename('zone');

  // ---------- Part A: per-scene NDVI and LST by zone ----------
  var scenes = load(aoi, 'LANDSAT/LT05/C02/T1_L2', 'ST_B6', 'SR_B3', 'SR_B4', '1984-01-01', '2012-06-01')
    .merge(load(aoi, 'LANDSAT/LE07/C02/T1_L2', 'ST_B6', 'SR_B3', 'SR_B4', '1999-01-01', L7_END))
    .merge(load(aoi, 'LANDSAT/LC08/C02/T1_L2', 'ST_B10', 'SR_B4', 'SR_B5', '2013-01-01', '2027-01-01'))
    .merge(load(aoi, 'LANDSAT/LC09/C02/T1_L2', 'ST_B10', 'SR_B4', 'SR_B5', '2021-01-01', '2027-01-01'));

  var table = scenes.map(function (img) {
    var st = img.select('ST');
    var clear = img.select('QA_PIXEL').bitwiseAnd(63).eq(0).and(st.neq(0));  // also drops snow
    var lst = st.multiply(0.00341802).add(149.0).subtract(273.15);
    var red = img.select('RED').multiply(0.0000275).add(-0.2);
    var nir = img.select('NIR').multiply(0.0000275).add(-0.2);
    var ndvi = nir.subtract(red).divide(nir.add(red)).clamp(-1, 1);
    var clear01 = clear.unmask(0);
    var stack = ee.Image.constant(1).rename('n')
      .addBands(clear01.rename('clear'))
      .addBands(ndvi.unmask(0).multiply(clear01).rename('ndvi'))
      .addBands(lst.unmask(0).multiply(clear01).rename('lst'))
      .addBands(zone).toFloat();
    var groups = ee.List(stack.reduceRegion({
      reducer: ee.Reducer.sum().repeat(4).group({groupField: 4, groupName: 'zone'}),
      geometry: aoi, scale: SCALE, maxPixels: 1e9, tileScale: 2
    }).get('groups'));
    var props = ee.Dictionary({
      city: city,
      scene_id: img.get('LANDSAT_PRODUCT_ID'),
      sensor: img.get('SPACECRAFT_ID'),
      date: img.date().format('YYYY-MM-dd'),
      sun_elevation: img.get('SUN_ELEVATION')
    });
    [0, 1, 2, 3].forEach(function (z) {
      var sums = ee.List(ee.Dictionary(groups.get(z)).get('sum'));
      props = props
        .set('z' + z + '_n', sums.get(0)).set('z' + z + '_clear', sums.get(1))
        .set('z' + z + '_ndvi', sums.get(2)).set('z' + z + '_lst', sums.get(3));
    });
    return ee.Feature(null, props);
  });
  Export.table.toDrive({
    collection: ee.FeatureCollection(table),
    description: city + '_scene_ndvi',
    folder: 'UHI_Prairie',
    fileFormat: 'CSV'
  });

  // ---------- Part B: AAFC Annual Crop Inventory classes per year ----------
  var rural = zone.eq(2);
  var aci = ee.ImageCollection('AAFC/ACI').filterBounds(aoi);
  var crops = aci.map(function (img) {
    var lc = img.select('landcover');
    var hRural = lc.updateMask(rural).reduceRegion({
      reducer: ee.Reducer.frequencyHistogram(), geometry: aoi, scale: 30,
      maxPixels: 1e10, tileScale: 4}).get('landcover');
    var hBox = lc.reduceRegion({
      reducer: ee.Reducer.frequencyHistogram(), geometry: aoi, scale: 30,
      maxPixels: 1e10, tileScale: 4}).get('landcover');
    return ee.Feature(null, {
      city: city,
      year: img.date().get('year'),
      rural: ee.String.encodeJSON(hRural),
      box: ee.String.encodeJSON(hBox)
    });
  });
  Export.table.toDrive({
    collection: ee.FeatureCollection(crops),
    description: city + '_aci_classes',
    folder: 'UHI_Prairie',
    fileFormat: 'CSV'
  });
});

print('ACI years available:', ee.ImageCollection('AAFC/ACI').aggregate_array('system:index'));
Map.setCenter(-106.67, 52.13, 10);
"""

out = ROOT / "gee" / "05_rural_greenness_crops.js"
out.write_text(JS.replace("__BOUNDARIES__", boundaries), encoding="utf-8")
print("wrote", out, round(out.stat().st_size / 1024), "KB")
